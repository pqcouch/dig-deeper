# ----- helpers ---------------------------------------------------------------

# lowercase + keep only a-z0-9 (for matching folder/file names loosely)
function Get-Norm([string]$s) {
    return ([regex]::Replace($s.ToLowerInvariant(), '[^a-z0-9]', ''))
}

# translate a forward-slash relative path into a full filesystem path
function Get-FsPath([string]$rel) {
    return (Join-Path $Root ($rel -replace '/', [IO.Path]::DirectorySeparatorChar))
}

# pull the <title> text out of an HTML file (fallback: the file name)
function Get-HtmlTitle([string]$path) {
    try {
        $content = [IO.File]::ReadAllText($path)
        $m = [regex]::Match($content, '<title>([^<]*)</title>')
        if ($m.Success -and $m.Groups[1].Value.Trim()) {
            return $m.Groups[1].Value.Trim()
        }
    } catch { }
    return [IO.Path]::GetFileNameWithoutExtension($path)
}

