function Get-Rank([string]$n) {
    if ($RankMap.ContainsKey($n)) { return [int]$RankMap[$n] }
    return 999
}

# immediate canonical-book subfolders of a directory (rel path, forward slash)
function Get-MemberSubdirs([string]$relDir) {
    $full = Get-FsPath $relDir
    $subs = Get-ChildItem -LiteralPath $full -Directory -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -notlike '_*' -and $_.Name -notlike '.*' -and (Get-Rank (Get-Norm $_.Name)) -ne 999 }
    return @($subs)
}

# a folder is a "collection" if it holds >=1 immediate canonical-book subfolder
function Test-Collection([string]$relDir) {
    return ((Get-MemberSubdirs $relDir).Count -gt 0)
}

# count HTML docs (excluding index.html) directly inside a dir
function Get-HtmlCount([string]$relDir) {
    $full = Get-FsPath $relDir
    $files = Get-ChildItem -LiteralPath $full -Filter *.html -File -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -ne 'index.html' }
    return @($files).Count
}

# ordinal (LC_ALL=C) name sort of a set of FileSystemInfo objects
# Sort-Object's string comparison is culture-aware even with -CaseSensitive
# (e.g. it can order "dig-...html" before "Ezekiel-...html"), which would
# disagree with bash's byte-value LC_ALL=C sort. Use a true ordinal compare.
function Sort-Ordinal($items) {
    $arr = @($items)
    [Array]::Sort($arr, [Comparison[object]]{ param($a, $b) [string]::CompareOrdinal($a.Name, $b.Name) })
    return $arr
}

# classify one html file by its base name -> @(group, label, chip)
#   group 1=overview 2=synthesis 3=sweep 4=sermon 5=other
function Get-Classify([string]$name) {
    $b = $name.ToLowerInvariant()
    if     ($b -like '*overview*')                                    { return @(1, 'Book Overview', 'big') }
    elseif ($b -like '*macro-synthesis*' -or $b -like '*macrosynthesis*') { return @(2, 'Macro-Synthesis', 'big') }
    elseif ($b -like '*sweep*')                                       { return @(3, 'Whole-Letter Sweep', '') }
    elseif ($b -like '*point-purpose*' -or $b -like '*sermon*')       { return @(4, 'Sermon Plan', '') }
    else                                                              { return @(5, '. ', '') }
}

# write a file unless -Dry; UTF-8 (no BOM), LF newlines, single trailing newline
function Write-Page([string]$relOut, [string]$content) {
    if ($Dry) {
        Write-Host "   [dry-run] would write: $relOut"
    } else {
        $content = ($content -replace "`r`n", "`n")
        $utf8 = New-Object System.Text.UTF8Encoding($false)
        [IO.File]::WriteAllText((Get-FsPath $relOut), $content + "`n", $utf8)
        Write-Host "   wrote: $relOut"
    }
}

