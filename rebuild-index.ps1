<#
=============================================================================
  rebuild-index.ps1  -  Dig Deeper study-library index builder (Windows)
-----------------------------------------------------------------------------
  Windows PowerShell port of rebuild-index.command. Run it (or double-click
  rebuild-index.bat, which launches this) to (re)build the catalogue pages for
  your Bible-study library. It:

    1. writes the TOP-LEVEL  index.html  (a portal listing every book that has
       HTML documents, in canonical Bible order), and
    2. writes a per-book  index.html  inside any book folder that doesn't
       already have a hand-made one.

  It NEVER touches your study documents, and it NEVER overwrites a hand-made
  index (one that lacks the "auto-generated" marker below). So a curated page
  like the Philippians index is safe; only auto pages are refreshed.

  To preview without writing anything, run:   .\rebuild-index.ps1 -Dry
  (or set the DRY environment variable to any value).
=============================================================================
#>

