}

# ----- build one book's index.html -------------------------------------------
function Build-BookIndex([string]$dir, [string]$backHref = '../index.html', [string]$backLabel = 'Study Library') {
    $idx = "$dir/index.html"
    $idxFull = Get-FsPath $idx
    if ((Test-Path -LiteralPath $idxFull) -and -not (Select-String -LiteralPath $idxFull -SimpleMatch $Mark -Quiet)) {
        Write-Host " $([char]0x00B7) ${dir}: keeping hand-made index.html (not overwritten)"
        return
    }

    $headDocs = New-Object System.Collections.ArrayList
    $passageRows = New-Object System.Collections.ArrayList
    $otherDocs = New-Object System.Collections.ArrayList

    $files = Sort-Ordinal (Get-ChildItem -LiteralPath (Get-FsPath $dir) -Filter *.html -File -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -ne 'index.html' })

    foreach ($f in $files) {
        $base = $f.Name
        $title = Get-HtmlTitle $f.FullName
        $stem = [IO.Path]::GetFileNameWithoutExtension($base)
        $pm = [regex]::Match($stem, '-([0-9]+)-([0-9]+)(?:to([0-9]+))?$')
        if ($pm.Success) {
            $ch = $pm.Groups[1].Value
            $v1 = $pm.Groups[2].Value
            if ($pm.Groups[3].Success) {
                $disp = "$ch`:$v1" + [char]0x2013 + $pm.Groups[3].Value
            } else {
                $disp = "$ch`:$v1"
            }
            $key = '{0:D3}{1:D5}' -f [int]$ch, [int]$v1
            [void]$passageRows.Add([pscustomobject]@{ Key = $key; Disp = $disp; Base = $base; Title = $title })
        } else {
            $cls = Get-Classify $base
            $grp = [int]$cls[0]; $label = $cls[1]; $chip = $cls[2]
            $card = '<a class="card" href="{0}"><span class="ref {1}">{2}</span><h3>{3}</h3></a>' -f $base, $chip, $label, $title
            if ($grp -ge 1 -and $grp -le 4) {
                [void]$headDocs.Add([pscustomobject]@{ Grp = $grp; Card = $card })
            } else {
                [void]$otherDocs.Add($card)
            }
        }
    }

    $orient = (($headDocs | Sort-Object Grp, Card | ForEach-Object { $_.Card }) -join "`n")
    $passages = (($passageRows | Sort-Object Key | ForEach-Object {
        '<a class="card" href="{0}"><span class="ref">{1}</span><h3>{2}</h3></a>' -f $_.Base, $_.Disp, $_.Title
    }) -join "`n")
    $other = ($otherDocs -join '')

    $body = '<header class="masthead"><h1>{0}</h1>' -f $dir
    $body += '<p class="subtitle">Dig Deeper study documents for {0}. Each card opens an HTML report; the same studies also exist as .odt and .md alongside.</p>' -f $dir
    $body += '<p class="meta"><a href="{0}" style="color:var(--accent)">&larr; {1}</a></p></header>' -f $backHref, $backLabel
    if ($orient)   { $body += '<h2 class="section">Orientation</h2><div class="grid two lead">{0}</div>' -f $orient }
    if ($passages) { $body += '<h2 class="section">Passage studies</h2><div class="grid two">{0}</div>' -f $passages }
    if ($other)    { $body += '<h2 class="section">Other documents</h2><div class="grid two">{0}</div>' -f $other }
    $body += '<footer><p>Auto-generated by <code>rebuild-index.command</code>. To give this book a richer, hand-written page, replace this file and it will be left alone from then on.</p></footer>'

    Write-Page $idx (Get-PageShell ("$dir " + [char]0x2014 + " Study Library") $body)
}

# ----- build a collection's index.html (e.g. Torah, The Twelve) --------------
function Build-CollectionIndex([string]$dir) {
    $idx = "$dir/index.html"
    $idxFull = Get-FsPath $idx
    $protected = $false
    if ((Test-Path -LiteralPath $idxFull) -and -not (Select-String -LiteralPath $idxFull -SimpleMatch $Mark -Quiet)) {
        $protected = $true
        Write-Host " $([char]0x00B7) ${dir}: keeping hand-made collection index.html (not overwritten)"
    }

    # (a) the collection's own top-level documents (overview / synthesis / etc.)
    $ownParts = New-Object System.Collections.ArrayList
    $files = Sort-Ordinal (Get-ChildItem -LiteralPath (Get-FsPath $dir) -Filter *.html -File -ErrorAction SilentlyContinue |
        Where-Object { $_.Name -ne 'index.html' })
    foreach ($f in $files) {
        $base = $f.Name
        $title = Get-HtmlTitle $f.FullName
        $cls = Get-Classify $base
        $label = $cls[1]; $chip = $cls[2]
        $ownParts.Add(('<a class="card" href="{0}"><span class="ref {1}">{2}</span><h3>{3}</h3></a>' -f $base, $chip, $label, $title)) | Out-Null
    }
    $own = ($ownParts -join '')

    # (b) member books, in canonical order; build each one's own index too
    $rows = New-Object System.Collections.ArrayList
    foreach ($sub in (Get-ChildItem -LiteralPath (Get-FsPath $dir) -Directory -ErrorAction SilentlyContinue)) {
        $sn = $sub.Name
        if ($sn -like '_*' -or $sn -like '.*') { continue }
        $r = Get-Rank (Get-Norm $sn)
        if ($r -eq 999) { continue }
        $rel = "$dir/$sn"
        $n = Get-HtmlCount $rel
        [void]$rows.Add([pscustomobject]@{ Rank = $r; Name = $sn; Count = $n })
        Build-BookIndex $rel '../index.html' $dir
    }
    $members = (($rows | Sort-Object Rank | ForEach-Object {
        $pl = if ($_.Count -eq 1) { 'document' } else { 'documents' }
        '<a class="card" href="{0}/index.html"><span class="ref">{1} {2}</span><h3>{0}</h3></a>' -f $_.Name, $_.Count, $pl
    }) -join "`n")

    if ($protected) { return }

    $body = '<header class="masthead"><h1>{0}</h1>' -f $dir
    $body += '<p class="subtitle">A collection: whole-of-{0} studies, plus a page for each book within it. Every HTML study also exists as .odt and .md alongside it.</p>' -f $dir
    $body += '<p class="meta"><a href="../index.html" style="color:var(--accent)">&larr; Study Library</a></p></header>'
    if ($own)     { $body += ('<h2 class="section">{0} {1} overview &amp; synthesis</h2><div class="grid two lead">{2}</div>' -f $dir, ([char]0x2014), $own) }
    if ($members) { $body += '<h2 class="section">Books</h2><div class="grid three">{0}</div>' -f $members }
    $body += '<footer><p>Auto-generated by <code>rebuild-index.command</code>. This is a collection page; each book nested inside <code>{0}/</code> keeps its own page and links back here.</p></footer>' -f $dir

    Write-Page $idx (Get-PageShell ("$dir " + [char]0x2014 + " Study Library") $body)
}

# ----- gather books & build --------------------------------------------------
Write-Host "Rebuilding library indexes in: $Root"
if ($Dry) { Write-Host ("(DRY RUN " + [char]0x2014 + " nothing will be written)") }
Write-Host ""

$bookRows = New-Object System.Collections.ArrayList   # Rank, Name, Count, Kind
$pending = New-Object System.Collections.ArrayList     # folders with material but no html yet

$topDirs = Sort-Ordinal (Get-ChildItem -LiteralPath $Root -Directory -ErrorAction SilentlyContinue |
    Where-Object { $_.Name -notlike '.*' })

foreach ($d in $topDirs) {
    $name = $d.Name
    if (Test-Collection $name) {
        Build-CollectionIndex $name
        $r = Get-Rank (Get-Norm $name)
        $members = (Get-MemberSubdirs $name).Count
        [void]$bookRows.Add([pscustomobject]@{ Rank = $r; Name = $name; Count = $members; Kind = 'collection' })
        continue
    }
    $n = Get-HtmlCount $name
    if ($n -eq 0) {
        $md = Get-ChildItem -LiteralPath $d.FullName -File -ErrorAction SilentlyContinue |
            Where-Object { $_.Extension -eq '.md' -or $_.Extension -eq '.odt' }
        if (@($md).Count -gt 0) { [void]$pending.Add($name) }
        continue
    }
    $r = Get-Rank (Get-Norm $name)
    [void]$bookRows.Add([pscustomobject]@{ Rank = $r; Name = $name; Count = $n; Kind = 'book' })
    Build-BookIndex $name
}

# ----- top-level portal ------------------------------------------------------
$sorted = @($bookRows | Sort-Object Rank)

function Emit-Cards([string]$which) {
    $rows = $sorted | Where-Object {
        $rk = $_.Rank
        if     ($which -eq 'OT') { $rk -le 39 }
        elseif ($which -eq 'NT') { $rk -ge 40 -and $rk -le 66 }
        else                     { $rk -ge 900 }
    }
    return (($rows | ForEach-Object {
        if ($_.Kind -eq 'collection') {
            $pl = if ($_.Count -eq 1) { 'book' } else { 'books' }
        } else {
            $pl = if ($_.Count -eq 1) { 'document' } else { 'documents' }
        }
        '<a class="card" href="{0}/index.html"><span class="ref">{1} {2}</span><h3>{0}</h3></a>' -f $_.Name, $_.Count, $pl
    }) -join "`n")
}

$otCards = Emit-Cards 'OT'
$ntCards = Emit-Cards 'NT'
$otherCards = Emit-Cards 'OTHER'
$bookcount = $sorted.Count
$today = (Get-Date).ToString('d MMMM yyyy', [Globalization.CultureInfo]::GetCultureInfo('en-GB'))

$pbody = '<header class="masthead"><h1>Dig Deeper ' + [char]0x2014 + ' Study Library</h1>'
$pbody += '<p class="subtitle">A growing library of Bible-study material: whole-book overviews, cross-passage syntheses, and passage-by-passage exegetical reports.</p>'
$pbody += ('<p class="meta">Local catalogue &middot; {0} book(s) with HTML &middot; rebuilt {1}</p></header>' -f $bookcount, $today)

if (Test-Path -LiteralPath (Get-FsPath 'preaching-toolkit-guide.html')) {
    $pbody += '<div class="grid lead"><a class="card" href="preaching-toolkit-guide.html"><span class="ref big">Guide</span><h3>About the Preaching Toolkit</h3><p>How the overviews, sweeps, digs and syntheses fit together.</p></a></div>'
}

if ($otCards)    { $pbody += '<h2 class="section">Old Testament</h2><div class="grid three">{0}</div>' -f $otCards }
if ($ntCards)    { $pbody += '<h2 class="section">New Testament</h2><div class="grid three">{0}</div>' -f $ntCards }
if ($otherCards) { $pbody += '<h2 class="section">Other</h2><div class="grid three">{0}</div>' -f $otherCards }

$pfoot = '<footer><p>This is a local index. Every link is a file in this folder tree, so the whole library works offline &mdash; just open <code>index.html</code> and click through. Nothing is published online.</p>'
if ($pending.Count -gt 0) {
    $pfoot += '<p>Also in the library, not yet rendered to HTML: {0}.</p>' -f ($pending -join ', ')
}
$pfoot += '<p>To refresh this catalogue after adding material, double-click <code>rebuild-index.command</code>. Hand-made book pages are never overwritten.</p></footer>'
$pbody += $pfoot

Write-Page 'index.html' (Get-PageShell ('Dig Deeper ' + [char]0x2014 + ' Study Library') $pbody)

Write-Host ""
Write-Host "Done. Open  index.html  in your browser."
